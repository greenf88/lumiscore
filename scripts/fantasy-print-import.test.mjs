import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const dir=new URL('../catalog/fantasy-descriptions-20261029/',import.meta.url);
const read=name=>readFileSync(new URL(name,dir),'utf8');
const proposal=read('print-editions-production.sql'),apply=read('print-editions-production-apply.sql');
const rollback=read('print-editions-rollback.sql');
async function database(){
 const db=new PGlite();
 await db.exec(`create table authors(id bigint primary key,name text);
 create table works(id bigint primary key,title text,open_library_id text,first_publish_year int,author_id bigint references authors);
 create table editions(id bigint generated by default as identity primary key,work_id bigint references works,title text,
 isbn_10 text,isbn_13 text,language text,publisher text,open_library_edition_id text,created_at timestamptz default now());
 create table ratings(id int primary key,work_id bigint references works,score int);
 create table progress(id int primary key,work_id bigint references works,status text);
 insert into authors values(11,'Mary Shelley'),(17,'Ursula K. Le Guin');
 insert into works values(14,'Frankenstein; or, The Modern Prometheus','OL450063W',1818,11),(22,'A Wizard of Earthsea','OL59798W',1968,17);
 insert into editions(work_id,title,isbn_13,language,publisher,open_library_edition_id) values
 (14,'FRANKENSTEIN. Bilingüe','9788415089452',null,'Plutón Ediciones','OL26385062M'),
 (22,'A Wizard of Earthsea (The Earthsea Cycle, Book 1)','9780563389163',null,'BBC Pubns','OL10635933M');
 update editions set id=14 where id=1;update editions set id=22 where id=2;
 select setval(pg_get_serial_sequence('public.editions','id'),22,true);
 insert into ratings values(1,14,8),(2,22,9);insert into progress values(1,14,'read'),(2,22,'reading');`);
 return db;
}
const rows=async(db,sql)=>(await db.query(sql)).rows;
const receipt=result=>result.find(r=>r.rows?.some(row=>row.action==='added English print edition'))?.rows??[];
const undo=(saved,commit=false)=>rollback.replace("'[]'::jsonb","'"+JSON.stringify(saved).replaceAll("'","''")+"'::jsonb")
 .replace(/rollback;\s*$/,commit?'commit;':'rollback;');

test('exact production files dry-run, apply, replay and receipt rollback preserve original/user records',async()=>{
 const db=await database();try{
  const old=await rows(db,'select * from editions order by id');
  assert.equal(receipt(await db.exec(proposal)).length,2);
  assert.deepEqual(await rows(db,'select * from editions order by id'),old);
  const saved=receipt(await db.exec(apply));assert.equal(saved.length,2);
  assert.equal((await rows(db,'select * from editions')).length,4);
  assert.equal(receipt(await db.exec(apply)).length,0);
  await db.exec(undo(saved));assert.equal((await rows(db,'select * from editions')).length,4);
  await db.exec(undo(saved,true));await db.exec(undo(saved,true));
  assert.deepEqual(await rows(db,'select * from editions order by id'),old);
  assert.deepEqual(await rows(db,'select score from ratings order by id'),[{score:8},{score:9}]);
  assert.deepEqual(await rows(db,'select status from progress order by id'),[{status:'read'},{status:'reading'}]);
 }finally{await db.close();}
});
test('an unexpected original value blocks the import without overwriting it',async()=>{
 const db=await database();try{
  await db.exec("update editions set language='eng' where id=14");
  await assert.rejects(db.exec(apply),/Original edition value changed/);await db.exec('rollback');
  assert.equal((await rows(db,'select * from editions')).length,2);
 }finally{await db.close();}
});
test('rollback stops at a later legitimate edition change',async()=>{
 const db=await database();try{
  const saved=receipt(await db.exec(apply));await db.exec("update editions set publisher='Later reviewed publisher' where isbn_13='9780553383041'");
  await assert.rejects(db.exec(undo(saved,true)),/Later legitimate edition change/);await db.exec('rollback');
  assert.equal((await rows(db,'select * from editions')).length,4);
 }finally{await db.close();}
});
test('rollback stops at an edition dependency, never cascades into user records',async()=>{
 const db=await database();try{
  const saved=receipt(await db.exec(apply));await db.exec('create table edition_usage(edition_id bigint references editions);insert into edition_usage values('+saved[0].edition_id+')');
  await assert.rejects(db.exec(undo(saved,true)),/Later edition dependency/);await db.exec('rollback');
  assert.equal((await rows(db,'select * from editions')).length,4);
 }finally{await db.close();}
});
