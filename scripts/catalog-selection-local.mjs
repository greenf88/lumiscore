// Local-only database harness: no env credentials, remote URLs or Supabase writes.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { buildPlan } from './catalog-selection-core.mjs';
import { importSelection, livePlan } from './catalog-selection-db.mjs';
import { reviewedInput } from './catalog-selection-inputs.mjs';
export const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const json=async name=>JSON.parse(await fs.readFile(path.join(root,'catalog/selection-v1',name),'utf8'));
export async function inputs() {
  const {records,pins,manifest}=await reviewedInput();
  const snapshot=await json('database-matches.json');
  const translated=await json('translation-match.json');
  const identityFixture=await json(manifest.identity_fixture_file);
  return {records,pins,works:[...new Map([...snapshot.matches,translated,...identityFixture].map(w=>[w.id,w])).values()]};
}
export async function createLocalDatabase(directory, works) {
  if(directory)await fs.mkdir(path.dirname(directory),{recursive:true});
  const db=new PGlite(directory);
  await db.waitReady;
  const exists=(await db.query("select to_regclass('public.catalog_categories') as name")).rows[0].name;
  if(exists)return db;
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create table public.authors(id bigint generated by default as identity primary key,name text not null);
    create table public.works(id bigint generated by default as identity primary key,title text not null,
      author_id bigint references public.authors(id),open_library_id text unique, first_publish_year integer);
    create table public.editions(id bigint generated by default as identity primary key,work_id bigint references public.works(id),
      title text,isbn_10 text,isbn_13 text,language text,open_library_edition_id text);
    grant select on public.authors, public.works, public.editions to anon,authenticated;
  `);
  await db.exec(await fs.readFile(path.join(root,'supabase/migrations/20260930185834_catalog_selection_v1.sql'),'utf8'));
  await db.transaction(async tx=>{
    const authors=new Map();
    for(const w of works) {
      if(!authors.has(w.author))authors.set(w.author,(await tx.query('insert into public.authors(name) values($1) returning id',[w.author??'Unknown (local snapshot)'])).rows[0].id);
      await tx.query('insert into public.works(id,title,author_id,open_library_id,first_publish_year) values($1,$2,$3,$4,$5)',
        [w.id,w.title,authors.get(w.author),w.open_library_id,w.first_publish_year??null]);
      for(const e of w.editions??[])await tx.query('insert into public.editions(work_id,title,isbn_10,isbn_13,language,open_library_edition_id) values($1,$2,$3,$4,$5,$6)',
        [w.id,e.title,e.isbn_10??null,e.isbn_13??null,e.language??null,e.open_library_edition_id??null]);
    }
    await tx.exec("select setval(pg_get_serial_sequence('public.works','id'),greatest((select max(id) from public.works),10000))");
  });
  return db;
}
export function localDirectory(value='outputs/catalog-selection-db') {
  const directory=path.resolve(root,value), allowed=path.join(root,'outputs')+path.sep;
  if(!directory.startsWith(allowed)||value.includes('://'))throw new Error('Only local directories inside this worktree/outputs are allowed');
  return directory;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const args=process.argv.slice(2);
  if(args.some(a=>a!=='--apply'&&!a.startsWith('--local-dir=')))throw new Error('Allowed: --apply --local-dir=outputs/name');
  const {records,pins,works}=await inputs();
  const apply=args.includes('--apply');
  let result;
  if(!apply) result={...buildPlan(records,works,pins),applied:false,mode:'snapshot dry-run; no database opened'};
  else {
    const directory=localDirectory(args.find(a=>a.startsWith('--local-dir='))?.slice(12));
    const db=await createLocalDatabase(directory,works);
    try {
      const plan=await livePlan(db,records,pins);
      result=await importSelection(db,records,pins,plan,{apply:true});
    } finally {await db.close();}
  }
  console.log(JSON.stringify(result,null,2));
}
